// Generates public/api/lead/labels.php (option + service names per locale) from the i18n JSON,
// so the lead e-mail shows human-readable values. Runs automatically before `astro build`.
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
const dir = new URL('../src/i18n/locales/', import.meta.url);
const out = {};
for (const L of readdirSync(dir)) {
  const f = JSON.parse(readFileSync(new URL(`${L}/contact.json`, dir), 'utf8')).form;
  const s = JSON.parse(readFileSync(new URL(`${L}/services.json`, dir), 'utf8')).items;
  out[L] = {
    types: f.types, locations: f.locations, statuses: f.statuses, preferred: f.preferredOptions,
    services: Object.fromEntries(Object.entries(s).map(([k, v]) => [k, v.name])),
  };
}
const php = `<?php\n// GENERATED by scripts/gen-lead-labels.mjs — do not edit by hand.\nreturn json_decode(${JSON.stringify(JSON.stringify(out)).replace(/\$/g, '\\$')}, true);\n`;
writeFileSync(new URL('../public/api/lead/labels.php', import.meta.url), php);
console.log('lead labels:', Object.keys(out).join(', '));
